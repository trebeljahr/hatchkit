/**
 * The procedure: how to cut a release, what each channel does on the
 * tag, what a person still owes afterwards, and how to read the status
 * table.
 */
export function renderReleasingDoc(config: ReleaseConfig): string {
  const { project, channels, policy, compat } = config;
  const pm = project.packageManager;
  const cut = scriptCommand(pm, "release", "X.Y.Z");
  const cutDry = scriptCommand(pm, "release", "X.Y.Z --dry-run");
  const status = scriptCommand(pm, "release:status");
  const exampleTag = `${project.tagPrefix}X.Y.Z`;

  const out: string[] = [];
  out.push(`# Releasing ${project.name}`, "", generatedNotice(), "");

  out.push(
    `A release is one git tag, ${code(exampleTag)}. ${code(cut)} cuts it and pushes nothing.`,
  );
  if (channels.length > 0) {
    out.push(
      `Pushing the tag starts the channel workflows below. ${code(status)} then tells you what each one did.`,
    );
  }
  out.push("");

  // -- Channels -----------------------------------------------------------
  out.push("## What the tag ships", "");
  if (channels.length === 0) {
    out.push(
      "This project has no release channels yet. A tag records the version and starts nothing.",
      `Enable a surface, run ${code("hatchkit update")}, and its channel appears here.`,
      "",
    );
  } else {
    out.push("| Channel | Workflow | What the tag does | What you still do |");
    out.push("|---|---|---|---|");
    for (const channel of channels) {
      out.push(
        `| ${cell(channel.label)} | ${code(channel.workflowFile)} | ${tagEffectCell(channel)} | ${gateCell(channel.gate)} |`,
      );
    }
    out.push("");
    const gated = channels.filter((channel) => channel.gate !== null);
    if (gated.length > 0) {
      out.push(
        `A green workflow is not yet a release for ${sentenceList(gated.map((channel) => channel.label))}. ` +
          "Each one needs the step in the last column before anybody has the new version.",
        "",
      );
    }
  }

  // -- Version copies -----------------------------------------------------
  out.push("## Where the version is written", "");
  out.push(
    config.versionCopies.length === 0
      ? `${code(project.versionFile)} holds the one version, and nothing else keeps a copy of it. The cut command sets it.`
      : `${code(project.versionFile)} holds the one version. The cut command sets it, and sets every copy below to the same value.`,
    "",
  );
  if (config.versionCopies.length > 0) {
    out.push("| File | Copy |");
    out.push("|---|---|");
    for (const copy of config.versionCopies) {
      out.push(`| ${code(copy.path)} | ${cell(copy.label)} |`);
    }
    out.push("");
    out.push(
      "The generated version-sync test asserts each of these. It fails until they agree, which is before anything is uploaded.",
      "",
    );
  }
  if (config.versionReads.length > 0) {
    out.push(
      `These read the version at build time instead of keeping a copy: ${sentenceList(config.versionReads.map((read) => read.label))}.`,
      "The same test pins that, so a later refactor cannot turn a build-time read back into a literal.",
      "",
    );
  }

  // -- Steps --------------------------------------------------------------
  out.push("## Cutting a release", "");
  const record = policy.rules.find(
    (rule): rule is Extract<PolicyRule, { kind: "release-record" }> =>
      rule.kind === "release-record",
  );
  let step = 1;

  if (record !== undefined) {
    out.push(
      `${step}. **Write the record.** ${code(record.path)} needs a heading for this version and a description of what changed.`,
      "   The policy check refuses the tag without it.",
      "",
    );
    step += 1;
  }

  out.push(
    `${step}. **Cut the tag.**`,
    "",
    "   ```bash",
    `   ${cutDry}`,
    `   ${cut}`,
    "   ```",
    "",
    `   The dry run prints the plan and writes nothing. The real run sets the version, runs the policy check,`,
    project.testCommand === null
      ? "   then commits and creates the annotated tag. It pushes nothing."
      : `   runs ${code(project.testCommand)}, then commits and creates the annotated tag. It pushes nothing.`,
    "",
  );
  step += 1;

  out.push(
    `${step}. **Push the branch, then the tag.**`,
    "",
    "   ```bash",
    "   git push origin main",
    `   git push origin ${exampleTag}`,
    "   ```",
    "",
    "   The workflows build what GitHub has, not your local checkout. Push the commit first.",
    "",
  );
  step += 1;

  out.push(
    `${step}. **Read the result.** Run ${code(status)}, or open the newest Release Summary run for the tag on GitHub.`,
    "",
  );
  step += 1;

  const gates = channels.filter(
    (channel): channel is ReleaseChannel & { gate: ChannelGate } => channel.gate !== null,
  );
  if (gates.length > 0) {
    out.push(`${step}. **Finish what the workflows cannot.**`, "");
    for (const channel of gates) {
      out.push(`   - ${channel.label}: ${channel.gate.note}`);
    }
    out.push("");
  }

  // -- Policy -------------------------------------------------------------
  out.push("## What the policy check refuses", "");
  if (policy.rules.length === 0) {
    out.push("This project has no policy rules. Nothing blocks a tag.", "");
  } else {
    out.push(
      `${code("node scripts/release-policy-check.mjs " + exampleTag)} runs these rules. The cut command runs the same check before it writes a file,`,
      "and the release workflow runs it again on the tagged commit.",
      "",
    );
    for (const rule of policy.rules) {
      const prose = policyRuleProse(rule, config);
      const blocking = policy.warnOnly.includes(rule.id)
        ? "_Reported; does not block._"
        : "_Blocks the release._";
      out.push(`- **${code(rule.id)}** — refuses ${prose.refuses}. ${prose.why} ${blocking}`);
    }
    out.push("");
  }

  // -- Status table -------------------------------------------------------
  out.push("## Reading the status table", "");
  out.push(
    `${code(status)} reads the newest run of each channel workflow for the tag, through ${code("gh api")} only. It changes nothing.`,
    "Each row is one channel: its label, its workflow, the run's result as a link, and the facts the run produced.",
    "",
  );
  if (channels.some((channel) => channel.uploadSteps.length > 0)) {
    out.push(
      "The facts come from named steps inside the run. A renamed step turns its fact into `unknown` rather than into a wrong answer.",
      "",
    );
  }
  const missing = channels.filter((channel) => channel.missingRunNote !== null);
  if (missing.length > 0) {
    out.push("A missing run is expected for these:", "");
    for (const channel of missing) {
      out.push(`- ${channel.label}: ${channel.missingRunNote}`);
    }
    out.push("");
  }
  out.push(
    "On GitHub the same table is the step summary of the newest `Release Summary` run for the tag.",
    "Each channel workflow finishing starts a fresh one, so the last summary is the whole picture.",
    "",
  );
  if (channels.some((channel) => channel.gate?.kind === "draft-release")) {
    out.push(
      "That summary runs with a read-only token, and GitHub shows draft releases to write access only.",
      `It reports no release for the tag until you publish the draft. Run ${code(status)} locally for that one fact.`,
      "",
    );
  }

  // -- Compat -------------------------------------------------------------
  if (compat !== null) {
    out.push("## Cross-version compatibility", "");
    out.push(
      "`.github/workflows/compat.yml` runs on every pull request to `main`, in both directions, against the previous stable tag:",
      "",
      "- **New client, old server.** This checkout's suite against the previous release's server image.",
      "- **Old client, new server.** The previous release's suite against a server image built from this checkout.",
      "",
      "Self-hosted servers lag and store clients lead, so old and new meet in the field either way.",
      "This is the mechanical check that the minimum levels each release declares are honest.",
      "",
      "Each direction skips with a notice, never a failure: the first while no release tag exists,",
      `the second while no tag contains ${code(compat.suiteEntry)} yet.`,
      "",
      "A refusal the suite makes on purpose, because a peer is below the declared minimum, is the expected answer.",
      "Any other refusal fails the job. Raise the declared minimum, or fix the change that broke the peer.",
      "",
    );
  }

  // -- Provenance ---------------------------------------------------------
  out.push("## Where this comes from", "");
  out.push(
    `${code(RELEASE_CONFIG_FILENAME)} lists the channels, the version copies, the credential groups and the policy rules.`,
    "`scripts/release.mjs`, `scripts/release-status.mjs` and `scripts/release-policy-check.mjs` read it and hold no knowledge of any one channel.",
    `Change the project, run ${code("hatchkit update")}, and this page changes with it.`,
    "",
  );

  return markdownFile(out);
}

