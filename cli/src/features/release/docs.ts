/*
 * cli/src/features/release/docs.ts — the two generated Markdown
 * documents of the `release` feature: `docs/releasing.md` (the
 * procedure) and `docs/release-credentials.md` (the secrets).
 *
 * WHY THESE ARE GENERATED RATHER THAN WRITTEN
 * -------------------------------------------
 * A hand-written release doc describes the channels a project had on
 * the day somebody wrote it. Add a store six months later and the doc is
 * wrong in the one place people trust it: what the tag will do. Both
 * documents here are a projection of the {@link ReleaseConfig}, so they
 * name the channels the project has and nothing else. A project with one
 * web deploy gets a short true page, not a long page about stores it
 * does not ship to.
 *
 * Both renderers are pure functions of the config — no disk, no
 * network, no clock. That is what lets the tests assert on the text for
 * any config shape, including the empty one, and it is why every
 * "degrades cleanly" branch below is reachable in a unit test.
 *
 * House style for the prose: one idea per sentence, active voice, and
 * every claim checkable in the generated project. When a fact is not in
 * the config, these documents do not invent it.
 */

import {
  type AbsentBehaviour,
  type ChannelGate,
  type CredentialGroup,
  type PolicyRule,
  RELEASE_CONFIG_FILENAME,
  type ReleaseChannel,
  type ReleaseConfig,
} from "./types.js";

// ---------------------------------------------------------------------------
// Small shared helpers
// ---------------------------------------------------------------------------

/** A Markdown code span. Written as concatenation because these files
 *  build their output from ordinary string literals, not template
 *  literals — backticks and `${` both appear in the output verbatim. */
const code = (value: string): string => "`" + value + "`";

/** Makes a value safe inside a Markdown table cell. A pipe would end
 *  the cell and a newline would end the row; both appear in
 *  hand-written `note` and `what` strings. */
const cell = (value: string): string => value.replace(/\|/g, "\\|").replace(/\s*\n\s*/g, " ");

/** Joins a list into English: "a", "a and b", "a, b and c". */
function sentenceList(items: readonly string[]): string {
  if (items.length === 0) return "";
  if (items.length === 1) return items[0];
  return `${items.slice(0, -1).join(", ")} and ${items[items.length - 1]}`;
}

/** How this project invokes one of its own package scripts. npm always
 *  needs `run`, and needs `--` before arguments of its own; pnpm and yarn
 *  take the script name directly and pass arguments through. */
function scriptCommand(
  packageManager: ReleaseConfig["project"]["packageManager"],
  script: string,
  args = "",
): string {
  if (packageManager === "npm") {
    return args === "" ? `npm run ${script}` : `npm run ${script} -- ${args}`;
  }
  return args === "" ? `${packageManager} ${script}` : `${packageManager} ${script} ${args}`;
}

/** Joins the collected lines into a finished document: no run of blank
 *  lines longer than one, and exactly one trailing newline. The section
 *  builders below push a blank after every block whether or not the next
 *  block arrives, which is what keeps each of them independent. */
function markdownFile(lines: readonly string[]): string {
  return `${lines
    .join("\n")
    .replace(/\n{3,}/g, "\n\n")
    .trimEnd()}\n`;
}

/** The notice both documents open with. Placed directly under the title
 *  so it is the first thing a reader meets, in the rendered page and in
 *  the raw file alike — whichever one they are about to edit. */
function generatedNotice(): string {
  return (
    `_Generated by ${code("hatchkit update")} from ${code(RELEASE_CONFIG_FILENAME)}. ` +
    "Edits to this file are lost on the next run. Change the project, then run " +
    `${code("hatchkit update")} again._`
  );
}

/** One sentence naming the consequence of a missing credential set. The
 *  wording is fixed per behaviour so the same absence always reads the
 *  same way, wherever it is reported. */
function absentSentence(absent: AbsentBehaviour): string {
  switch (absent) {
    case "skip":
      return "The upload step does not run. The build still runs, and its output stays attached to the workflow run.";
    case "unsigned":
      return "The artifact is built without a signature. It is not uploaded anywhere a person could install it from.";
    case "fail":
      return "The workflow fails. This channel cannot degrade.";
  }
}

/** The same fact in a table cell, where the row already carries the
 *  channel name. */
function absentCell(absent: AbsentBehaviour): string {
  switch (absent) {
    case "skip":
      return "Upload skipped; the build is still attached to the run";
    case "unsigned":
      return "Built unsigned and not uploaded";
    case "fail":
      return "The workflow fails";
  }
}

/** What a person still owes after the workflow turns green. */
function gateCell(gate: ChannelGate | null): string {
  return gate === null ? "Nothing" : cell(gate.note);
}

/** What the tag starts, for the channel table. Two channels never have a
 *  run for the tag, for different reasons, and a reader who does not
 *  know which one they are looking at waits for a run that was never
 *  going to arrive. */
function tagEffectCell(channel: ReleaseChannel): string {
  if (channel.trigger === "branch") {
    return `Nothing — this workflow runs on a push to the default branch, not on a tag. ${cell(channel.effect)}`;
  }
  if (channel.trigger === "tag-dispatch") {
    return `Nothing until you dispatch it from the tag, in Actions → ${cell(channel.workflowName)}. ${cell(channel.effect)}`;
  }
  return cell(channel.effect);
}

// ---------------------------------------------------------------------------
// Policy rules, in prose
// ---------------------------------------------------------------------------

/** What a rule refuses, and why that refusal is worth having. Derived
 *  from the rule's `kind` so a new rule kind cannot ship undocumented:
 *  the compiler reports the missing branch. */
function policyRuleProse(
  rule: PolicyRule,
  config: ReleaseConfig,
): { refuses: string; why: string } {
  const versionFile = code(config.project.versionFile);
  switch (rule.kind) {
    case "version-matches-tag":
      return {
        refuses: `a tag whose number differs from the version in ${versionFile}`,
        why: "The tag names the release. A mismatch ships a build under a number nobody can look up.",
      };
    case "version-copies-match":
      return {
        refuses: `a release where a copy of the version disagrees with ${versionFile}`,
        why: "One stale copy ships the previous number to that one surface, and only that surface.",
      };
    case "no-prerelease-to-public": {
      const names = rule.channels.map((id) => channelLabel(config, id));
      return {
        refuses: `a prerelease tag while ${sentenceList(names)} distribute publicly`,
        why: "People who did not ask for a prerelease would be given one.",
      };
    }
    case "credential-set-complete":
      return {
        refuses: `a half-set of the ${channelLabel(config, rule.channelId)} credentials (${rule.secrets.map(code).join(", ")})`,
        why: "Half a set builds the artifact and then uploads nothing, or uploads it unsigned.",
      };
    case "no-unsigned-publish":
      return {
        refuses: `publishing ${channelLabel(config, rule.channelId)} while ${sentenceList(rule.signingSecrets.map(code))} ${rule.signingSecrets.length === 1 ? "is" : "are"} absent`,
        why: "An unsigned build must not reach a person who can install it.",
      };
    case "tag-is-new":
      return {
        refuses: "a tag that is not newer than the newest release tag that already exists",
        why: "Version numbers only go forward. Every reader that compares them assumes that.",
      };
    case "release-record":
      return {
        refuses: `a release with no heading for this version in ${code(rule.path)}`,
        why: "Somebody deciding whether to upgrade has to be able to read what changed.",
      };
  }
}

/** A channel id turned into its label, or the raw id when the channel is
 *  gone. An unknown id is a derivation bug, so the doc prints it rather
 *  than hiding it. */
function channelLabel(config: ReleaseConfig, channelId: string): string {
  return config.channels.find((channel) => channel.id === channelId)?.label ?? channelId;
}

