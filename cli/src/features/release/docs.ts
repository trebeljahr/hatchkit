/**
 * The secrets: what each channel needs, where each value comes from,
 * what happens without it, and the one-time steps a vendor forces
 * through a UI.
 *
 * Names only. A value never reaches this file, because the file is
 * committed.
 */
export function renderCredentialsDoc(config: ReleaseConfig): string {
  const out: string[] = [];
  out.push(`# Release credentials — ${config.project.name}`, "", generatedNotice(), "");

  if (config.credentials.length === 0) {
    out.push(...noCredentialsBody(config));
    return markdownFile(out);
  }

  out.push(
    "Every channel of this project, and what it does when its credentials are absent.",
    "No value belongs in this file: it holds secret **names** only, and it is committed.",
    "",
  );

  // -- The whole picture, one table ---------------------------------------
  const groupByChannel = new Map<string, CredentialGroup>();
  for (const group of config.credentials) groupByChannel.set(group.channelId, group);

  out.push("| Channel | Secrets | When they are absent |");
  out.push("|---|---|---|");
  for (const channel of config.channels) {
    const group = groupByChannel.get(channel.id);
    const secrets = group?.secrets.map((secret) => secret.name) ?? channel.credentials;
    if (secrets.length === 0) {
      out.push(`| ${cell(channel.label)} | none | Publishes with the workflow's own token |`);
      continue;
    }
    out.push(
      `| ${cell(channel.label)} | ${secrets.map(code).join(", ")} | ${absentCell(group?.absent ?? channel.absent)} |`,
    );
  }
  // A group whose channel is gone is a derivation bug. Print it rather
  // than dropping a credential requirement on the floor.
  for (const group of config.credentials) {
    if (config.channels.some((channel) => channel.id === group.channelId)) continue;
    out.push(
      `| ${cell(group.label)} | ${group.secrets.map((secret) => code(secret.name)).join(", ")} | ${absentCell(group.absent)} |`,
    );
  }
  out.push("");

  out.push(
    `Set one with ${code("gh secret set <NAME>")} from the repository, or in Settings → Secrets and variables → Actions.`,
    "",
  );

  // -- One section per group ----------------------------------------------
  for (const group of config.credentials) {
    out.push(`## ${group.label}`, "");
    out.push("| Secret | What it is | Where it comes from |");
    out.push("|---|---|---|");
    for (const secret of group.secrets) {
      out.push(`| ${code(secret.name)} | ${cell(secret.what)} | ${cell(secret.where)} |`);
    }
    out.push("");

    out.push("**When these are absent.**", "");
    out.push(`${absentSentence(group.absent)} ${group.absentNote}`, "");

    if (group.manualSteps.length > 0) {
      out.push(
        "**One-time setup.** These cannot be automated; the vendor forces each one through its own UI.",
        "",
      );
      group.manualSteps.forEach((manualStep, index) => out.push(`${index + 1}. ${manualStep}`));
      out.push("");
    }
  }

  const halfSetRules = config.policy.rules.filter(
    (rule): rule is Extract<PolicyRule, { kind: "credential-set-complete" }> =>
      rule.kind === "credential-set-complete",
  );
  if (halfSetRules.length > 0) {
    const guarded = sentenceList(halfSetRules.map((rule) => channelLabel(config, rule.channelId)));
    out.push("## Half a set is refused", "");
    out.push(
      `The policy check refuses a release where the credentials of ${guarded} are partly set.`,
      "Half a set is the shape that builds an artifact and then uploads nothing, or uploads it unsigned.",
      "Set all of a group, or none of it.",
      "",
    );
  }

  return markdownFile(out);
}

/** The honest short version, for a project whose channels need nothing
 *  beyond the workflow's own token. An empty skeleton of headings would
 *  read as a document somebody forgot to finish. */
function noCredentialsBody(config: ReleaseConfig): string[] {
  if (config.channels.length === 0) {
    return [
      "This project has no release channels yet, so there is no credential to set.",
      `Enable a surface and run ${code("hatchkit update")}. A channel that needs a secret gets a section here.`,
      "",
    ];
  }
  const labels = sentenceList(config.channels.map((channel) => channel.label));
  return [
    `No channel of this project needs a credential. The workflow's own ${code("GITHUB_TOKEN")} covers ${labels}.`,
    "There is nothing to set in Settings → Secrets and variables → Actions, and nothing to rotate.",
    `Enable a surface that publishes elsewhere, run ${code("hatchkit update")}, and its secrets get a section here.`,
    "",
  ];
}
