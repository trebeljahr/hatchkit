/** What the feature needs, in the words the CLI shows people. */
export const RAYCAST_PREREQUISITE =
  "the shared client core (packages/core + packages/shared) and a server runtime";

/**
 * Null when `surfaces` can carry the launcher, otherwise the sentence to show.
 *
 * Shared by the create flow, the non-interactive validator and
 * `hatchkit update`, so the three cannot answer differently.
 */
export function raycastPrerequisiteProblem(surfaces: Surface): string | null {
  if (surfaces === "static") {
    return "The `raycast` feature needs a server runtime: the launcher has no cookie jar, so it signs in through the server's device flow and carries a bearer token. A `static` project has no server. Pick `fullstack` or `split`.";
  }
  if (surfaces === "backend") {
    return "The `raycast` feature needs a web app: a pairing code is approved on one, and every command that cannot do something opens it. A `backend` project ships no client. Pick `fullstack` or `split`.";
  }
  return null;
}

const RAYCAST_ID: FeatureId = "raycast";

export const raycastFeature = registerFeature({
  /**
   * Annotated through `FeatureId`, never asserted into it. The annotation is
   * what proves the `Feature` union names this id; an `as FeatureId` would
   * survive a rename or a typo and the only symptom would be a feature that
   * is never offered.
   */
  id: RAYCAST_ID,
  title: "Raycast launcher extension",
  summary:
    "Five launcher commands over the shared client core, with a store-publishable export and a vendored copy of the kit.",
  // Referenced through the definition rather than by string, so importing
  // this feature registers the one it needs — an id the registry has never
  // seen reads as "unknown feature", not as a prerequisite.
  requires: [clientCoreFeature.id],
  // A pairing code is approved on a web page and the bearer token comes from
  // a server's device flow, so neither half can be missing.
  surfaces: ["fullstack", "split"],
  // Everything it writes is its own directory plus add-only root scripts, so
  // `update` can add it to a project that has been running for months.
  addableAfterScaffold: true,
  apply(ctx: FeatureContext): void {
    ctx.log("  raycast: launcher extension over the shared client kit");
    for (const line of applyRaycast(ctx)) ctx.log(`  ${line}`);
    for (const conflict of ctx.ledger.conflicts()) {
      ctx.log(`  raycast: ${conflict.file} — ${conflict.detail ?? "not applied"}`);
    }
  },
  plannedFiles(ctx: FeaturePlanContext): readonly string[] {
    return raycastPlannedFiles(ctx);
  },
});
