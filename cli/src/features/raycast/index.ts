/*
 * cli/src/features/raycast/index.ts — the `raycast` feature.
 *
 * It adds `packages/raycast`: a macOS launcher extension with five commands,
 * bound to the shared client core rather than reimplementing any of it, and
 * two build scripts that produce and verify a standalone, store-publishable
 * copy of the package.
 *
 * ============================================================
 * WHAT IT IS, AND WHAT IT DELIBERATELY IS NOT
 * ============================================================
 *
 * It is a UI SHELL. The offline queue, the optimistic overlay, the read
 * cache, the drain-before-read rule, the queue-behind-writes rule, the replay
 * classifier and the per-origin capability cache are all `@starter/core`'s,
 * and the package binds Raycast's `LocalStorage` to the kit's one storage seam
 * and calls into it. A second copy of any of those would fork this surface's
 * behaviour from every other client's — silently, because a queue that
 * replays slightly differently still replays.
 *
 * It is NOT a second pairing mechanism. Auth is the shared device grant —
 * better-auth's RFC 8628 plus `bearer()` — with the token in Raycast's
 * encrypted store and `clientId` read from `identifiers.clientIds.raycast`.
 *
 * ============================================================
 * THE PREREQUISITE, AND WHY IT IS NOT AN IMPORT
 * ============================================================
 *
 * `requires: ["client-core"]` although the launcher never imports
 * `@starter/core`: it imports `src/vendor/`, a generated byte-for-byte copy.
 * The Raycast Store builds an extension ALONE with a plain `npm install`,
 * where a `workspace:*` dependency cannot resolve at all, so a workspace
 * import would be a package that builds here and nowhere else.
 *
 * The prerequisite is still real and still enforced, because the GENERATOR
 * reads `packages/core/src` and `packages/shared/src`. Without them
 * `pnpm run vendor:raycast` has nothing to copy, and the extension's own test
 * run fails on the first check.
 *
 * ============================================================
 * WHY THE WORKSPACE PACKAGE IS NOT `@<scope>/raycast`
 * ============================================================
 *
 * Raycast reads `package.json`'s `name` as the extension's store slug, which
 * must be a bare lowercase identifier — and pnpm reads the same field as the
 * workspace package name. One field, two readers, so the workspace name is the
 * store slug. That slug and the publisher handle together key Raycast's
 * encrypted per-extension store, which is why both are frozen at scaffold
 * time and why the package's PUBLISHING.md says what changing one costs.
 */

