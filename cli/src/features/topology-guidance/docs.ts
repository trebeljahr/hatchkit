/** Render `docs/deploy-topology.md` for one project: the four facts,
 *  the symptom table, the one-time platform setup and the verification
 *  commands, all carrying that project's own hosts.
 *
 *  Rendered for single-origin projects too, with the facts stated as
 *  the constraints a later split will meet. A project that has not
 *  split yet is exactly the project about to walk into them. */
export function renderTopologyDoc(project: OperationalProject): string {
  const h = hostsOf(project);
  const layout = recommendedDomainLayout({
    domain: project.domain,
    topology: project.topology,
    surfaces: project.surfaces,
  });
  const lines: string[] = [];

  // The document is owned by hatchkit and rewritten whole on every run,
  // so it has to say so: a reader who edits it here loses the edit on
  // the next `hatchkit update`, and the only way to find that out
  // otherwise is to lose one.
  lines.push(OWNED_FILE_NOTICE);
  lines.push("");
  lines.push(`# Deploying ${project.name}`);
  lines.push("");
  lines.push(
    h.split
      ? `Two applications on two hosts of the \`${h.zone}\` zone. Each one deploys, restarts and fails on its own.`
      : `One application on \`${h.web || h.api}\`, serving every half of the project from a single origin.`,
  );
  lines.push("");
  lines.push("| Application | Serves | Routed at |");
  lines.push("| --- | --- | --- |");
  for (const app of layout.apps) {
    const appName = h.split ? `\`${project.name}-${app.role}\`` : `\`${project.name}\``;
    lines.push(
      `| ${appName} | ${app.serves} | ${app.hosts.map((x) => `\`https://${x}\``).join(", ")} |`,
    );
  }
  lines.push("");

  lines.push("## 1. Two applications, not one");
  lines.push("");
  lines.push(
    "The unit of deployment is the application. Everything inside one restarts together, so one application holding both halves means a change to the browser bundle restarts the API with it.",
  );
  lines.push("");
  lines.push(
    "That drops every connection the server was holding — open sockets, in-flight uploads, live subscriptions — for a change that never touched the server. Two applications restart independently, which is the whole reason for the split.",
  );
  if (!h.split) {
    lines.push("");
    lines.push(
      `This project runs **one** application today. A deploy of the site restarts the API. Split it when the server starts holding connections that a site deploy must not break.`,
    );
  }
  lines.push("");

  lines.push("## 2. The service name inside each compose file is load-bearing");
  lines.push("");
  lines.push(
    "The platform keys its domain routing by compose service name. It does not validate the key against the compose file.",
  );
  lines.push("");
  lines.push(
    "A key naming a service that is not declared is accepted by the API with a success response, emits no proxy labels at all, and leaves the site answering a gateway error. **A 200 from the API and a broken site is the signature of this bug** — nothing in the dashboard reports it, because as far as the platform is concerned the write succeeded.",
  );
  lines.push("");
  if (h.split) {
    lines.push(
      "So the service names in `docker-compose.client.yml` and `docker-compose.server.yml` (`client` and `server`) must stay exactly as they are. Renaming a service without changing the routing entry is a silent outage.",
    );
  } else {
    lines.push(
      "So the service names in `docker-compose.yml` must match the routing entries exactly. Renaming a service without changing the routing entry is a silent outage.",
    );
  }
  lines.push("");

  lines.push("## 3. The split is by host, never by path");
  lines.push("");
  lines.push(
    "Serving the API from a path on the site's host looks like the cheaper answer: one hostname, one DNS record, one certificate, and the browser stays same-origin. It does not work, for two independent reasons, and either one is fatal.",
  );
  lines.push("");
  lines.push(
    "**The proxy merges site blocks for the same host.** Two applications on one host both write the same site. The merge keeps one of them, and the winner swallows the other's traffic — so a request for the API is answered by the site's own 404 page. There is no more-specific-rule-wins ordering to rely on here.",
  );
  lines.push("");
  lines.push(
    "**The matched path prefix is stripped.** Even with the order forced, a route matched on `/api` delivers the request with `/api` removed. The API mounts its own routes *at* `/api`, so it receives `/trpc` where it expects `/api/trpc` and answers 404 to everything.",
  );
  lines.push("");
  lines.push(
    "Each application therefore needs a host of its own, and each host routes at `/`, where nothing is stripped. **Never put a path in an application's domain field.**",
  );
  lines.push("");

  lines.push("## 4. A host of its own needs a certificate that covers it");
  lines.push("");
  lines.push(
    `A wildcard certificate covers exactly ONE label below its zone: a certificate for \`${h.zone}\` covers \`${h.zone}\` and \`*.${h.zone}\`, and nothing deeper.`,
  );
  lines.push("");
  lines.push(
    "A host two labels below the zone fails the TLS handshake before any HTTP happens. No routing check tells you anything useful behind that, because no request is ever made:",
  );
  lines.push("");
  lines.push("```");
  lines.push("curl: (35) error:0A000410:SSL routines::sslv3 alert handshake failure");
  lines.push("```");
  lines.push("");
  if (h.api) {
    const depthNote = layout.wildcardTrap
      ? `\`${h.api}\` is more than one label below \`${h.zone}\`, so the zone's wildcard does **not** cover it.`
      : `\`${h.api}\` is one label below \`${h.zone}\`, so the zone's wildcard covers it.`;
    lines.push(depthNote);
    lines.push("");
  }
  lines.push(
    "This is the constraint that decides where a project's domain can live. When the API host would sit deeper than one label, there are three ways out, cheapest-correct first:",
  );
  lines.push("");
  // Stated even for a project that is fine today: the project about to
  // move its domain under an existing zone is exactly this one.
  const alternatives = layout.wildcardTrap
    ? layout.alternatives
    : wildcardAlternatives(h.api || `api.${h.zone}`, h.zone);
  alternatives.forEach((alt, i) => {
    lines.push(`${i + 1}. **${alt.title}** — ${alt.detail} Cost: ${alt.cost}.`);
  });
  lines.push("");

  lines.push("## Reading a broken deploy");
  lines.push("");
  lines.push("| Symptom | Cause | Where to look |");
  lines.push("| --- | --- | --- |");
  lines.push(
    "| 404 from the API host, while the site works | the matched path prefix was stripped | the application's domain field — make it a bare host with no path |",
  );
  lines.push(
    "| the site's own 404 page from the API host | two applications are claiming the same site | the two applications' domain fields — they must not share a host |",
  );
  lines.push(
    "| a gateway error (502 / 503) from a healthy application | no usable proxy labels were emitted | the service names in the routing entries against the compose file |",
  );
  lines.push(
    "| TLS handshake failure, before any HTTP | the host is more than one label under its zone | the certificate covering that host — a wildcard does not reach it |",
  );
  lines.push("");

  lines.push("## One-time setup on the platform");
  lines.push("");
  if (h.split) {
    lines.push("1. **Two applications**, both from this repository, build pack `dockercompose`:");
    lines.push("");
    for (const app of layout.apps) {
      const file =
        app.role === "server" ? "docker-compose.server.yml" : "docker-compose.client.yml";
      lines.push(
        `   - \`${project.name}-${app.role}\` → compose path \`${file}\`, domain \`https://${app.hosts[0]}\``,
      );
    }
    lines.push("");
    lines.push(
      "   Give each one a bare host and no path (fact 3), and never the same host as the other.",
    );
  } else {
    lines.push(
      `1. **One application** from this repository, build pack \`dockercompose\`, compose path \`docker-compose.yml\`, domain \`https://${h.web || h.api}\`.`,
    );
  }
  lines.push("");
  lines.push(
    `2. **DNS** on the \`${h.zone}\` zone: ${layout.dnsHosts.map((x) => `\`${x}\``).join(" and ")}. Every host an application carries needs a record before its certificate can be issued.`,
  );
  lines.push("");
  lines.push(
    "3. **Environment values on the application that runs the server.** Under a split the API and the site are separate origins, so the cross-origin settings stop being decorative: the server's own public origin, the site's origin, and the trusted-origin list are what make sign-in work at all. Getting them wrong breaks authentication for everyone, not just for one client.",
  );
  lines.push("");
  lines.push(
    "4. **The client's API origin is baked in at image build time.** It is a build argument, not a runtime value: a wrong value builds green and points the shipped bundle at a dead host. Changing it means rebuilding the image.",
  );
  lines.push("");

  lines.push("## Verifying a deploy");
  lines.push("");
  lines.push("```bash");
  if (h.api) lines.push(`curl -sS  ${h.apiOrigin}/api/health   # the server half`);
  if (h.web) lines.push(`curl -sSI ${h.webOrigin}/   # the client half`);
  lines.push("```");
  lines.push("");
  if (h.api) {
    lines.push(
      `The first request covers the whole server chain at once: the certificate on \`${h.api}\`, the route reaching the container with nothing stripped, and the server being up. Read a failure against the table above.`,
    );
    lines.push("");
    lines.push(
      `The API origin is an origin with no path — \`${h.apiOrigin}\` — and the clients append \`/api/...\` themselves. A request therefore reads \`${h.apiOrigin}/api/health\`${h.split ? ", with a doubled-looking `api` segment" : ""}. That is the mount, not a mistake in the value.`,
    );
  } else {
    lines.push("Read a failure against the table above.");
  }
  lines.push("");
  return `${lines.join("\n")}`;
}

