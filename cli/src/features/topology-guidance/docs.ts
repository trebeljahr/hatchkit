/*
 * The written form of the topology facts — one document for a person
 * reading a broken deploy, and one compact section for the agent memory
 * file of the project itself.
 *
 * ---------------------------------------------------------------------
 * Why generate this at all
 * ---------------------------------------------------------------------
 *
 * The four facts in ./advice.ts are checkable, and `hatchkit doctor`
 * checks them. But the checks only fire against a manifest hatchkit can
 * see. The failures themselves show up as four symptoms with no obvious
 * cause — a 404 from a host that resolves, a gateway error from an
 * application the dashboard calls healthy, a TLS handshake that fails
 * before any request exists — and the person reading them is usually
 * not the person who chose the topology. Every one of those symptoms
 * has exactly one cause, and the table below is the shortest path from
 * one to the other.
 *
 * The CLAUDE.md section exists for the same reason one level up: the
 * next agent to touch a project reads that file first, and "simplify
 * this to one application" or "serve the API from a path" are both
 * plausible-looking changes that re-create a solved outage. The section
 * states the reason, not the rule, because a rule without its reason is
 * the thing an agent optimizes away.
 *
 * ---------------------------------------------------------------------
 * Rules every transform here follows
 * ---------------------------------------------------------------------
 *
 *   1. The project's own hostnames, never an example. A document
 *      carrying someone else's domain is a document nobody checks their
 *      own values against.
 *   2. The CLAUDE.md retrofit is idempotent and anchored. It replaces
 *      what is between its markers, and when it cannot find a sane
 *      insertion point it returns the file UNCHANGED — a hand-written
 *      memory file is safer left alone than half-rewritten.
 */

import type { OperationalProject } from "../operational-context.js";
import {
  defaultApiOrigin,
  defaultWebOrigin,
  hasClientHalf,
  hasServerHalf,
} from "../operational-context.js";
import {
  inferZone,
  normalizeHost,
  recommendedDomainLayout,
  splitApiHost,
  wildcardAlternatives,
} from "./advice.js";

/** Where the generated document lands, relative to the project root. */
export const TOPOLOGY_DOC_REL = "docs/deploy-topology.md";

/** The first line of the generated document.
 *
 *  `writeIfChanged` overwrites, which is the right primitive for a file
 *  hatchkit regenerates from the manifest — and the wrong surprise for
 *  somebody who edited it. An owned file has to say it is owned, in the
 *  file, because that is the only place the person about to edit it is
 *  looking. */
export const OWNED_FILE_NOTICE =
  "<!-- Generated by hatchkit from .hatchkit.json. Rewritten on every `hatchkit update` — put your own notes in another file. -->";

/** Markers around the CLAUDE.md section. Stable strings: they are the
 *  only thing that makes a second run an update instead of a duplicate,
 *  so changing them orphans every section already written. */
/* The managed-section anchors.
 *
 * `hatchkit-managed:`, deliberately NOT `hatchkit:`. The `hatchkit:`
 * namespace belongs to the starter's own conditional-pruning syntax
 * (`hatchkit:if` / `hatchkit:endif`, see scaffold/claude-md.ts), which
 * is template machinery that must never survive into a generated
 * project — test-scaffold.ts asserts a scaffolded CLAUDE.md contains no
 * `hatchkit:` at all, and that assertion is worth keeping literally,
 * because anything matching it IS residue.
 *
 * These two are the opposite kind of marker: they are meant to survive,
 * so that a later `hatchkit update` can replace the section between
 * them instead of appending a second copy. A separate namespace keeps a
 * reader from mistaking one for the other.
 *
 * This is also why the section is NOT maintained with the ledger's
 * `ensureManagedBlock`, which is otherwise exactly the right primitive
 * for a region of a file the user also edits. That helper owns its own
 * marker syntax, and for CLAUDE.md it would emit two things this file
 * cannot have:
 *
 *   · `hatchkit:begin topology-guidance` — which the scaffold test
 *     reads as template residue and fails on.
 *   · a `#` comment prefix, because `inferCommentPrefix` has no rule
 *     for Markdown and falls back to it — so each marker would render
 *     as a top-level heading in the middle of the memory file.
 *
 * So the block stays hand-rolled, and {@link upsertClaudeMdSection} is
 * handed to `ledger.edit` as a fixed-point transform instead. It gets
 * the same two guarantees (replace in place, never duplicate) with an
 * HTML comment a Markdown reader does not see. */
export const CLAUDE_MD_BEGIN = "<!-- hatchkit-managed:topology-guidance -->";
export const CLAUDE_MD_END = "<!-- hatchkit-managed:end-topology-guidance -->";

/** Headings under which the section is a sane fit when no markers exist
 *  yet. Anything else is left alone — see rule 2 in the module header. */
const ANCHOR_HEADING = /^(#{2,4})\s+.*\b(deploy|deployment|hosting|infrastructure|production)\b/i;

interface Hosts {
  /** Hostname the site is served from, or "" when there is no site. */
  web: string;
  /** Hostname the API is served from, or "" when there is no API. */
  api: string;
  /** Origin the clients are built against. */
  apiOrigin: string;
  webOrigin: string;
  zone: string;
  split: boolean;
}

/** Resolve the hostnames a project actually has, so every sentence in
 *  the generated text can name one instead of describing one. */
function hostsOf(project: OperationalProject): Hosts {
  const domain = normalizeHost(project.domain);
  const split = project.topology === "split";
  const server = hasServerHalf(project.surfaces);
  const client = hasClientHalf(project.surfaces);
  const apiHost = split && client ? splitApiHost(domain) : domain;
  return {
    web: client ? domain : "",
    api: server ? apiHost : "",
    apiOrigin: defaultApiOrigin(domain, project.topology),
    webOrigin: defaultWebOrigin(domain),
    zone: inferZone(domain),
    split,
  };
}

