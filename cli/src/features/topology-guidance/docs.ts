/** The compact version, in the register of a project's agent-memory
 *  file: dense, reason first, no step-by-step. It is written to be read
 *  by whoever is about to "simplify" the deployment. */
export function renderClaudeMdSection(project: OperationalProject): string {
  const h = hostsOf(project);
  const lines: string[] = [];

  lines.push(CLAUDE_MD_BEGIN);
  lines.push(
    h.split
      ? `### Deployment (two applications, two hosts)`
      : `### Deployment (one application, one host)`,
  );
  lines.push("");
  if (h.split) {
    lines.push(
      `Production is two applications on two hosts of the \`${h.zone}\` zone: the site on \`${h.webOrigin}\` from \`docker-compose.client.yml\`, the API on \`${h.apiOrigin}\` from \`docker-compose.server.yml\`. Two applications rather than one so a site deploy cannot restart the server and drop every connected socket.`,
    );
  } else {
    lines.push(
      `Production is one application on \`${h.webOrigin}\`, from \`docker-compose.yml\`. Both halves restart together, so a site deploy also restarts the server and drops every connection it was holding. Split the deployment before that matters.`,
    );
  }
  lines.push("");
  lines.push(
    `The service name inside each compose file is load-bearing: the platform keys its domain routing by service name, and a key that matches no declared service is accepted with a 200, emits no proxy labels, and serves a gateway error. Success from the API plus a broken site means check the service names first.`,
  );
  lines.push("");
  lines.push(
    "**Never split the halves by path on one host.** The proxy merges same-host site blocks, so one application swallows the other's traffic, and it strips the matched prefix, so the API receives requests one segment short of the mount it serves. Each application gets a host of its own, routed at `/`.",
  );
  lines.push("");
  lines.push(
    `**A wildcard certificate covers one label below its zone.** \`*.${h.zone}\` covers \`${h.api || `api.${h.zone}`}\` only while that host is one label deep; two labels down, TLS fails before any HTTP and nothing downstream is diagnosable. This is what decides where the domain can live — an apex zone of its own is the cheap correct answer.`,
  );
  lines.push("");
  if (h.split) {
    lines.push(
      "Consequence: the API is a separate origin from the site. The cross-origin settings on the server (its own public origin, the site's origin, the trusted-origin list) are load-bearing, not decorative — do not simplify them away. The client's API origin is inlined at image build time, so a wrong value builds green and points at a dead host.",
    );
    lines.push("");
  }
  lines.push(`Full reasoning, symptoms and setup: \`${TOPOLOGY_DOC_REL}\`.`);
  lines.push(CLAUDE_MD_END);
  return lines.join("\n");
}

/** Insert or replace the section in an existing CLAUDE.md.
 *
 *  Three outcomes, and the third is the important one:
 *
 *    · markers present → the text between them is replaced, so running
 *      this twice is the same as running it once.
 *    · no markers, but a deployment-ish heading → the section is
 *      inserted after that section's body, before the next heading at
 *      the same or a higher level.
 *    · neither → the input is returned UNCHANGED. A memory file with no
 *      place for this is a file somebody wrote by hand, and appending
 *      to the end of it is how a generated block ends up stranded in
 *      the middle of unrelated prose. */
export function upsertClaudeMdSection(content: string, section: string): string {
  const begin = content.indexOf(CLAUDE_MD_BEGIN);
  const end = content.indexOf(CLAUDE_MD_END);
  if (begin !== -1 && end !== -1 && end > begin) {
    const head = content.slice(0, begin);
    const tail = content.slice(end + CLAUDE_MD_END.length);
    return `${head}${section}${tail}`;
  }

  const lines = content.split(/\r?\n/);
  const anchor = lines.findIndex((line) => ANCHOR_HEADING.test(line));
  if (anchor === -1) return content;

  const anchorMatch = ANCHOR_HEADING.exec(lines[anchor] ?? "");
  const anchorLevel = anchorMatch?.[1]?.length ?? 2;
  let insertAt = lines.length;
  for (let i = anchor + 1; i < lines.length; i++) {
    const heading = /^(#{1,6})\s/.exec(lines[i] ?? "");
    if (heading && heading[1].length <= anchorLevel) {
      insertAt = i;
      break;
    }
  }

  const before = lines.slice(0, insertAt);
  const after = lines.slice(insertAt);
  while (before.length > 0 && before[before.length - 1]?.trim() === "") before.pop();
  const rebuilt = [...before, "", section, "", ...after];
  return rebuilt.join("\n");
}
